"""
Network Traffic & Alert SQLAlchemy Models
"""

from datetime import datetime, timezone
from sqlalchemy import String, Float, Integer, Boolean, DateTime, Enum, Text, JSON
from sqlalchemy.orm import Mapped, mapped_column
import enum

from app.core.database import Base


class AlertSeverity(str, enum.Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class AlertStatus(str, enum.Enum):
    OPEN = "open"
    INVESTIGATING = "investigating"
    RESOLVED = "resolved"
    FALSE_POSITIVE = "false_positive"


class AttackType(str, enum.Enum):
    PORT_SCAN = "port_scan"
    BRUTE_FORCE = "brute_force"
    DOS = "dos"
    DDOS = "ddos"
    SQL_INJECTION = "sql_injection"
    XSS = "xss"
    MALWARE = "malware"
    DATA_EXFILTRATION = "data_exfiltration"
    ANOMALY = "anomaly"
    UNKNOWN = "unknown"


class NetworkEvent(Base):
    """Represents a captured network packet/flow."""
    __tablename__ = "network_events"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    src_ip: Mapped[str] = mapped_column(String(45), nullable=False, index=True)
    dst_ip: Mapped[str] = mapped_column(String(45), nullable=False, index=True)
    src_port: Mapped[int] = mapped_column(Integer, nullable=True)
    dst_port: Mapped[int] = mapped_column(Integer, nullable=True)
    protocol: Mapped[str] = mapped_column(String(10), nullable=True)
    packet_size: Mapped[int] = mapped_column(Integer, nullable=True)
    duration: Mapped[float] = mapped_column(Float, nullable=True)
    flags: Mapped[str] = mapped_column(String(50), nullable=True)
    # Features extracted for ML
    features: Mapped[dict] = mapped_column(JSON, nullable=True)
    # Anomaly score from ML model (0.0 - 1.0)
    anomaly_score: Mapped[float] = mapped_column(Float, nullable=True)
    is_anomalous: Mapped[bool] = mapped_column(Boolean, default=False)

    def __repr__(self) -> str:
        return f"<NetworkEvent id={self.id} {self.src_ip}->{self.dst_ip}>"


class Alert(Base):
    """Represents a security alert generated by the IDS."""
    __tablename__ = "alerts"

    id: Mapped[int] = mapped_column(primary_key=True, index=True)
    timestamp: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=True)
    severity: Mapped[AlertSeverity] = mapped_column(
        Enum(AlertSeverity), default=AlertSeverity.MEDIUM, nullable=False, index=True
    )
    status: Mapped[AlertStatus] = mapped_column(
        Enum(AlertStatus), default=AlertStatus.OPEN, nullable=False, index=True
    )
    attack_type: Mapped[AttackType] = mapped_column(
        Enum(AttackType), default=AttackType.UNKNOWN, nullable=False
    )
    src_ip: Mapped[str] = mapped_column(String(45), nullable=True, index=True)
    dst_ip: Mapped[str] = mapped_column(String(45), nullable=True)
    src_port: Mapped[int] = mapped_column(Integer, nullable=True)
    dst_port: Mapped[int] = mapped_column(Integer, nullable=True)
    anomaly_score: Mapped[float] = mapped_column(Float, nullable=True)
    # Link to the network event that triggered this alert
    network_event_id: Mapped[int] = mapped_column(Integer, nullable=True)
    # Analyst notes
    notes: Mapped[str] = mapped_column(Text, nullable=True)
    resolved_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=True)
    resolved_by: Mapped[int] = mapped_column(Integer, nullable=True)

    def __repr__(self) -> str:
        return f"<Alert id={self.id} severity={self.severity} status={self.status}>"
