"""
Detection models — NetworkEvent and Alert.
"""

from django.db import models


class NetworkEvent(models.Model):
    """Represents a captured network packet / flow submitted for analysis."""

    class Protocol(models.TextChoices):
        TCP = "TCP", "TCP"
        UDP = "UDP", "UDP"
        ICMP = "ICMP", "ICMP"
        OTHER = "OTHER", "Other"

    timestamp = models.DateTimeField(auto_now_add=True, db_index=True)
    src_ip = models.GenericIPAddressField(db_index=True)
    dst_ip = models.GenericIPAddressField(db_index=True)
    src_port = models.PositiveIntegerField(null=True, blank=True)
    dst_port = models.PositiveIntegerField(null=True, blank=True)
    protocol = models.CharField(max_length=10, choices=Protocol.choices, default=Protocol.TCP)
    packet_size = models.PositiveIntegerField(null=True, blank=True)
    duration = models.FloatField(null=True, blank=True, help_text="Duration in seconds")
    flags = models.CharField(max_length=100, blank=True, default="")
    features = models.JSONField(null=True, blank=True, help_text="Extracted ML features")

    # ML output
    anomaly_score = models.FloatField(null=True, blank=True, help_text="0.0–1.0 (higher = more anomalous)")
    is_anomalous = models.BooleanField(default=False, db_index=True)

    class Meta:
        ordering = ["-timestamp"]
        verbose_name = "Network Event"
        verbose_name_plural = "Network Events"

    def __str__(self):
        return f"[{self.timestamp:%Y-%m-%d %H:%M:%S}] {self.src_ip} → {self.dst_ip} (score={self.anomaly_score})"


class Alert(models.Model):
    """Security alert generated by the IDS."""

    class Severity(models.TextChoices):
        LOW = "low", "Low"
        MEDIUM = "medium", "Medium"
        HIGH = "high", "High"
        CRITICAL = "critical", "Critical"

    class Status(models.TextChoices):
        OPEN = "open", "Open"
        INVESTIGATING = "investigating", "Investigating"
        RESOLVED = "resolved", "Resolved"
        FALSE_POSITIVE = "false_positive", "False Positive"

    class AttackType(models.TextChoices):
        PORT_SCAN = "port_scan", "Port Scan"
        BRUTE_FORCE = "brute_force", "Brute Force"
        DOS = "dos", "DoS"
        DDOS = "ddos", "DDoS"
        SQL_INJECTION = "sql_injection", "SQL Injection"
        XSS = "xss", "XSS"
        MALWARE = "malware", "Malware"
        DATA_EXFILTRATION = "data_exfiltration", "Data Exfiltration"
        ANOMALY = "anomaly", "Anomaly"
        UNKNOWN = "unknown", "Unknown"

    timestamp = models.DateTimeField(auto_now_add=True, db_index=True)
    title = models.CharField(max_length=255)
    description = models.TextField(blank=True, default="")
    severity = models.CharField(
        max_length=20, choices=Severity.choices, default=Severity.MEDIUM, db_index=True
    )
    status = models.CharField(
        max_length=20, choices=Status.choices, default=Status.OPEN, db_index=True
    )
    attack_type = models.CharField(
        max_length=30, choices=AttackType.choices, default=AttackType.UNKNOWN
    )
    src_ip = models.GenericIPAddressField(null=True, blank=True, db_index=True)
    dst_ip = models.GenericIPAddressField(null=True, blank=True)
    src_port = models.PositiveIntegerField(null=True, blank=True)
    dst_port = models.PositiveIntegerField(null=True, blank=True)
    anomaly_score = models.FloatField(null=True, blank=True)
    network_event = models.ForeignKey(
        NetworkEvent,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="alerts",
    )
    notes = models.TextField(blank=True, default="")
    resolved_at = models.DateTimeField(null=True, blank=True)
    resolved_by = models.ForeignKey(
        "accounts.User",
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="resolved_alerts",
    )

    class Meta:
        ordering = ["-timestamp"]
        verbose_name = "Alert"
        verbose_name_plural = "Alerts"

    def __str__(self):
        return f"[{self.severity.upper()}] {self.title}"
